'''Interface candidates only. No actual connector, OCR, inference, storage or bank endpoint.'''
from __future__ import annotations
from typing import Protocol, Mapping, Any, Iterator
from pathlib import Path

class SourceAdapter(Protocol):
    def capabilities(self, config_ref: str) -> Mapping[str, bool]: ...
    def validate(self, config_ref: str, purpose: str) -> None: ...
    def fetch_change_page(self, cursor_token: str | None, selection_hash: str, page_size: int) -> Mapping[str, Any]: ...
    def fetch_object(self, external_object_id: str, source_revision: str | None) -> Mapping[str, Any]: ...
    def check_access(self, external_object_id: str, purpose: str) -> Mapping[str, Any]: ...

class LayoutAdapter(Protocol):
    def predict(self, input_path: Path, profile_ref: str, timeout_seconds: int) -> Mapping[str, Any]: ...

class VisionAdapter(Protocol):
    def extract(self, image_ref: str, ocr_context_ref: str, output_schema_ref: str,
                model_revision: str, timeout_seconds: int) -> Mapping[str, Any]: ...

class ConsumerAdapter(Protocol):
    def capability(self) -> Mapping[str, bool]: ...
    def invalidate(self, event_ref: str, idempotency_key: str) -> Mapping[str, Any]: ...
    def rebuild(self, event_ref: str, idempotency_key: str) -> Mapping[str, Any]: ...
    def query_receipt(self, event_id: str) -> Mapping[str, Any]: ...

# Mappings represent version-specific transport envelopes only; normative persisted payloads
# are the closed reference models. Raw provider output is archived, never treated as trusted data.
